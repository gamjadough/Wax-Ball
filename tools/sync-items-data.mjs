// Generate the new heart-only patch; never rewrite previously deployed migrations.
import {readFile,writeFile} from 'node:fs/promises';
import {itemData} from './items-service.mjs';
const file=new URL('../supabase/migrations/20261015074409_wax_heart_balance.sql',import.meta.url);
const heart=itemData.list.find(d=>d.group==='heart'),channels=JSON.stringify(Object.fromEntries(itemData.channels(heart)));
const sql=`-- Generated by tools/sync-items-data.mjs. Apply after 20261019_items_remake.sql.
-- Heart balance only: no inventory, effects, deadlines, prices or role changes.
begin;
do $balance$
declare source text;updated text;changed integer;
begin
 select pg_get_functiondef(to_regprocedure('public.wakppu_item_winners(jsonb,bigint)')) into source;
 if source is null then raise exception 'Existing item remake helper is required';end if;
 updated:=regexp_replace(source,$pattern$when it\\.channel='heart' then '[^']+'::jsonb$pattern$,
  $replacement$when it.channel='heart' then '${channels}'::jsonb$replacement$);
 if updated=source and position('${channels}' in source)=0 then raise exception 'Unexpected heart helper; balance patch aborted';end if;
 update public.wakppu_item_defs set value=${heart.value} where item_id='${heart.id}' and channel='heart' and seconds=${heart.seconds};
 get diagnostics changed=row_count;
 if changed<>1 then raise exception 'Expected exactly one existing heart definition';end if;
 if updated<>source then execute updated;end if;
end $balance$;
commit;
`;
if(process.argv.includes('--check')){if((await readFile(file,'utf8')).replaceAll('\r\n','\n')!==sql)throw new Error('Heart SQL configuration is out of date');}
else await writeFile(file,sql);
